# Generates the tiles and the per-frame cloud positions for nubo_dmg.asm and
# nubo_cgb.asm. Usage: python3 gen_data.py <output directory>
import math, sys
G = {
 'N': ["XX...XX","XXX..XX","XXXX.XX","XX.XXXX","XX..XXX","XX...XX","XX...XX"],
 'U': ["XX...XX","XX...XX","XX...XX","XX...XX","XX...XX","XX...XX",".XXXXX."],
 'B': ["XXXXXX.","XX...XX","XX...XX","XXXXXX.","XX...XX","XX...XX","XXXXXX."],
 'O': [".XXXXX.","XX...XX","XX...XX","XX...XX","XX...XX","XX...XX",".XXXXX."],
}
CLOUD = ["......XXXX..","..XX.XXXXXX.",".XXXXXXXXXX.",".XXXXXXXXXXX","XXXXoXXoXXXX","XXXXoXXoXXXX","XXXXXXXXXXXX","XXXXXXXXXXXX",".XXXXXXXXXX."]
CLOSED = [l if j != 4 else "XXXXXXXXXXXX" for j, l in enumerate(CLOUD)]
WORD = ['.'.join(G[c][r] for c in "NUBO") for r in range(7)]

def canvas(w, h): return [[0] * w for _ in range(h)]
def stamp(px, art, x0, y0):
    for j, line in enumerate(art):
        for i, ch in enumerate(line):
            if ch == 'X':
                for d in range(4):
                    px[y0 + 2*j + (d >> 1)][x0 + 2*i + (d & 1)] = 1
def tiles(px, cols, rows):
    out = []
    for ty in range(rows):
        for tx in range(cols):
            out.append([sum(px[ty*8 + r][tx*8 + i] << (7 - i) for i in range(8)) for r in range(8)])
    return out

# The name: 8x2 background tiles, drawn 2 pixels below the top of tile row 12.
name = canvas(64, 16); stamp(name, WORD, 0, 2)
# The cloud: 3x3 sprites, plus the middle tile of the second row with closed eyes.
cloud = canvas(24, 24); stamp(cloud, CLOUD, 0, 0)
closed = canvas(24, 24); stamp(closed, CLOSED, 0, 0)
all_tiles = tiles(name, 8, 2) + tiles(cloud, 3, 3) + [tiles(closed, 3, 3)[4]]
assert tiles(closed, 3, 3)[:4] == tiles(cloud, 3, 3)[:4] and tiles(closed, 3, 3)[5:] == tiles(cloud, 3, 3)[5:]

def ease(t): t = min(1, max(0, t)); return 1 - (1 - t) ** 3
REST_X, REST_Y, S = 34, 94, 2
xs, ys = [], []
for n in range(256):
    f = n - 1
    t = ease((f - 6) / 38)
    x = round(-26*S + (REST_X + 26*S) * t)
    bob = round(math.sin((f - 44) / 40 * 2 * math.pi) * S) if f > 44 else round(math.sin(f / 10) * 2 * S * (1 - t))
    xs.append((x + 8) & 0xFF)
    ys.append((REST_Y + bob + 16) & 0xFF)

def db(values): return '\n'.join('    db ' + ', '.join('$%02X' % v for v in values[i:i+16]) for i in range(0, len(values), 16))
out = sys.argv[1]
with open(f'{out}/nubo_tiles.inc', 'w') as f:
    f.write('; Generated by gen_data.py: the name, the cloud and its closed eyes, 8 bytes per tile\n')
    f.write(db([b for t in all_tiles for b in t]) + '\n')
with open(f'{out}/nubo_dmg_tables.inc', 'w') as f:
    f.write('; Generated by gen_data.py: the cloud sprite position (OAM X and Y) in every frame\n')
    f.write('SECTION "CloudX", ROM0[$0700]\nCloudX:\n' + db(xs) + '\n\n')
    f.write('SECTION "CloudY", ROM0[$0800]\nCloudY:\n' + db(ys) + '\n')
# The Game Boy Color boot ROM has less room. The art is drawn with 2x2 pixels,
# so every tile row appears twice and is a doubled 4-bit pattern: it stores one
# nibble per pair of rows, which SameBoy's DoubleBitsAndWriteRowTwice expands.
# The cloud's position is stored while it flies in (frames 7-45); after that it
# bobs, which repeats every 40 frames.
def nibble(row):
    bits = [(row >> (7 - i)) & 1 for i in range(8)]
    assert all(bits[i] == bits[i + 1] for i in range(0, 8, 2)), 'columns are not doubled'
    return sum(bits[2 * i] << (3 - i) for i in range(4))
assert all(t[r] == t[r + 1] for t in all_tiles for r in range(0, 8, 2)), 'rows are not doubled'
tile_nibbles = [nibble(t[r]) << 4 | nibble(t[r + 2]) for t in all_tiles for r in (0, 4)]
FLIGHT_START, FLIGHT_END = 7, 46
bob = [(REST_Y + round(math.sin(i / 40 * 2 * math.pi) * S) + 16) & 0xFF for i in range(40)]
assert all(ys[n] == bob[(n - 45) % 40] for n in range(46, 256))
assert all(xs[n] == xs[45] for n in range(45, 256))
# While flying in, each frame's position is packed in one byte: how many pixels
# the cloud moves right (high nibble) and its height, 8 being where it rests
# (low nibble).
REST_OAM_Y = REST_Y + 16
flight = []
for n in range(FLIGHT_START, FLIGHT_END):
    dx, dy = (xs[n] - xs[n - 1]) & 0xFF, ys[n] - REST_OAM_Y + 8
    assert 0 <= dx < 16 and 0 <= dy < 16, (n, dx, dy)
    flight.append(dx << 4 | dy)
with open(f'{out}/nubo_cgb_constants.inc', 'w') as f:
    f.write('; Generated by gen_data.py\n')
    f.write(f'DEF CLOUD_START_X EQU ${xs[FLIGHT_START - 1]:02X}  ; OAM X before it flies in (out of sight)\n')
    f.write(f'DEF CLOUD_REST_X EQU ${xs[FLIGHT_END - 1]:02X}   ; OAM X once it has arrived\n')
    f.write(f'DEF CLOUD_REST_Y EQU ${REST_OAM_Y:02X}   ; OAM Y at rest\n')
with open(f'{out}/nubo_cgb_data.inc', 'w') as f:
    f.write('; Generated by gen_data.py\n')
    f.write('; The name, the cloud and its closed eyes: two bytes per tile, each nibble\n; one pair of rows at half width\n')
    f.write('NuboTileNibbles:\n' + db(tile_nibbles) + '\nNuboTileNibblesEnd:\n')
    f.write('; While the cloud flies in (frames 7-45): how far it moves right (high nibble)\n; and its height (low nibble, 8 = at rest)\n')
    f.write('CloudFlight:\n' + db(flight) + '\n')
    f.write('; Then the OAM Y of every frame of its bob\n')
    f.write('CloudBobY:\n' + db(bob) + '\n')
print('tiles', len(all_tiles))
